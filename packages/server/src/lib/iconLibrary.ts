/**
 * Resolve an icon name to inline HTML.
 *  - Lucide-style names (`book-open`, `settings`) → inline SVG path
 *  - Material Icons (`mi-foo`) → `<span class="material-icons">foo</span>`
 *    (font ligature — the name is the text, not a class)
 *  - Heroicons (`hi-foo-solid|outline`) → inline SVG from HEROICONS
 *  - PrimeIcons (`pi pi-foo`), FontAwesome (`fa fa-foo`) → `<i class="…">`
 *  - Unknown → empty string (caller decides fallback)
 *
 * @param size Pixel size for the inline SVG variant. Ignored for icon
 *             fonts (those use font-size from CSS).
 */
export function iconHtml(name: string | undefined | null, size = 16): string {
  if (!name) return ''
  const trimmed = name.trim()
  // Material Icons render via a font LIGATURE, not a per-name class: the icon
  // name lives in the element's text and `.material-icons` (font-feature
  // `liga`) turns it into the glyph. Emitting `<i class="mi-foo">` (a class
  // the vendored material-icons.css never defines) rendered nothing. Mirrors
  // the dashboard's IconPicker: `<span class="material-icons">{name}</span>`.
  if (trimmed.startsWith('mi-')) {
    const ligature = trimmed.slice(3).replace(/[^a-z0-9_ ]/gi, '')
    return `<span class="material-icons" style="font-size:${size}px;line-height:1" aria-hidden="true">${ligature}</span>`
  }
  // Heroicons ship as static SVG (no font); inject the requested size.
  if (trimmed.startsWith('hi-')) {
    const svg = HEROICONS[trimmed]
    if (!svg) return ''
    return svg.replace('<svg ', `<svg width="${size}" height="${size}" `)
  }
  if (/^(pi pi-|fa fa-)/.test(trimmed)) {
    return `<i class="${trimmed}" style="font-size:${size}px;line-height:1"></i>`
  }
  const path = ICONS[trimmed]
  if (!path) return ''
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`
}
